import type { MissionSummary } from '../../domain/mission-summary'
import { formatStation } from '../../domain/station-label'
import { printAttachments } from '../../domain/attachments'
import { csvRow } from './csv'
import { AAR_CAPABILITY_LABELS } from '../services/aar-note.interface'

/**
 * E-189: the Mission summary as one CSV file - the snapshot to keep, stamped with when it was
 * generated and what window it covers. Sections follow one another, each with a heading row.
 * Pure (no DOM), so the layout can be tested without a browser.
 */

/** The identifying lines at the top of the screen, the printout and the file. */
export type SummaryStamp = {
  mission: string
  opPeriod: string
  /** Human text for the window, e.g. "Oct 15, 08:00 - Oct 15, 12:00". */
  windowLabel: string
  generatedBy: string
  exercise: boolean
}

const pad = (n: number) => String(n).padStart(2, '0')

/** Local `2026-10-15 14:30`: sortable, unambiguous in a spreadsheet. */
export function localStamp(d: Date): string {
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())} ${pad(d.getHours())}:${pad(d.getMinutes())}`
}

/** `rangertrak-summary-<mission>-2026-10-15-1430.csv` */
export function summaryCsvFilename(mission: string, now: Date): string {
  const label = (mission || 'mission').replace(/[^a-z0-9_-]+/gi, '_')
  const when = `${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())}-${pad(now.getHours())}${pad(now.getMinutes())}`
  return `rangertrak-summary-${label}-${when}.csv`
}

export function buildSummaryCsv(summary: MissionSummary, stamp: SummaryStamp): string {
  const lines: string[] = []
  const section = (heading: string, header: string[], rows: Array<Array<string | number>>) => {
    if (lines.length) lines.push('')
    lines.push(csvRow([heading]))
    lines.push(csvRow(header))
    for (const r of rows) lines.push(csvRow(r))
  }
  const t = summary.totals
  const w = summary.window

  section('Stamp', ['Item', 'Value'], [
    ['Mission', stamp.mission],
    ['Operational period', stamp.opPeriod],
    ['Window', stamp.windowLabel + (w.soFar ? ' (so far: the period has not ended)' : '')],
    ['Window from', localStamp(w.from)],
    ['Window to', localStamp(w.to)],
    ['Generated at', localStamp(summary.generatedAt)],
    ['Generated by', stamp.generatedBy],
    ['Marking', stamp.exercise ? 'EXERCISE' : ''],
  ])
  section('Totals', ['Item', 'Value'], [
    ['Radio log entries', t.entries],
    ['Stations heard', t.stations],
    ['First entry', t.first ? localStamp(t.first) : ''],
    ['Last entry', t.last ? localStamp(t.last) : ''],
    ['Edited after logging', t.revised],
    ['Logged more than 15 minutes late', t.late],
    ['Needing attention', t.attention],
  ])
  section(`Per bucket (${summary.buckets.hours} hour${summary.buckets.hours === 1 ? '' : 's'} each)`,
    ['Bucket start', 'Entries', 'Needing attention'],
    summary.buckets.items.map(b => [localStamp(b.start), b.count, b.attentionCount]))
  section('By team', ['Team', 'Entries'], summary.byTeam.map(r => [r.label, r.count]))
  section('By station', ['Station', 'Entries', 'Last heard'],
    summary.byStation.map(r => [r.station, r.count, localStamp(r.lastHeard)]))
  section('By operator', ['Operator', 'Entries'], summary.byOperator.map(r => [r.label, r.count]))
  section('By status', ['Status', 'Entries'], summary.byStatus.map(r => [r.status, r.count]))
  section('By source', ['Source', 'Entries'], summary.bySource.map(r => [r.label, r.count]))
  section('Needs attention', ['Time', 'Station', 'Status', 'Notes', 'Attachments'],
    summary.attention.map(e => [
      localStamp(new Date(e.date)),
      formatStation(e.tacticalCall, e.callsign) || '(no call sign)',
      e.status,
      e.notes,
      // E-194: name and short fingerprint of each live attachment.
      printAttachments(e).map(a => `${a.name}${a.smallerCopy ? ' (smaller copy)' : ''} (${a.fingerprint})`).join('; '),
    ]))
  section('AAR notes', ['Area', 'Noted at', 'Observation', 'Capability element', 'Recommendation', 'Owner'],
    summary.aar.groups.flatMap(g => g.notes.map(n => [
      g.area, n.createdAt, n.text, n.capability ? AAR_CAPABILITY_LABELS[n.capability] : '', n.recommendation ?? '', n.owner ?? '',
    ])))
  if (summary.aar.appCount) {
    lines.push('')
    lines.push(csvRow([`${summary.aar.appCount} note(s) about RangerTrak are on the AAR notes page and not listed here`]))
  }
  return lines.join('\r\n')
}
