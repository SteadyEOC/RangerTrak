#!/usr/bin/env node
/**
 * E-264 (tester, 2026-10-28: "Could a search bar be added to the documentation?"): builds the
 * search index for the /help page's tabs from their templates, so Help's search box (and the
 * 404 page, E-256) can find a section with no connection. The per-screen Guide text needs no
 * index: it is already data, in shared/guide/guide-content.ts, and the search reads it there.
 *
 * One entry per <h3> or <rangertrak-expandable-section summary="...">: the heading, the
 * element's id if it has one (else a slug of the heading, which HelpComponent.revealFragment
 * also understands), and the plain text up to the next heading.
 *
 *   node tools/help-index/build.js          writes src/app/shared/guide/help-index.generated.ts
 *   node tools/help-index/build.js --check  fails if that file is out of date (CI)
 */
const fs = require('fs')
const path = require('path')

const ROOT = path.join(__dirname, '..', '..')
const TABS = path.join(ROOT, 'src', 'app', 'lazy', 'help', 'tabs')
const OUT = path.join(ROOT, 'src', 'app', 'shared', 'guide', 'help-index.generated.ts')

// File name -> the `/help?tab=` key (shared/guide/help-sections.ts), in Help's tab order.
const FILES = [
  ['help-start.component.html', 'start'],
  ['help-faq.component.html', 'faq'],
  ['help-after-mission.component.html', 'after'],
  ['help-data.component.html', 'data'],
  ['help-about.component.html', 'about'],
  ['help-feedback.component.html', 'feedback'],
]

const ENTITIES = {
  amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ', rarr: '→', larr: '←',
  rsquo: '’', lsquo: '‘', rdquo: '”', ldquo: '“', mdash: '—', ndash: '–', middot: '·',
  hellip: '…', trade: '™', copy: '©', times: '×', deg: '°', check: '✓',
}

function decode(s) {
  return s
    .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)))
    .replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(Number(d)))
    .replace(/&([a-z]+);/gi, (m, n) => ENTITIES[n.toLowerCase()] ?? m)
}

/** Template markup to the words a reader sees: no tags, no Angular control flow or bindings. */
function plain(html) {
  return decode(html
    .replace(/\{\{[\s\S]*?\}\}/g, ' ')
    .replace(/@(if|else if|else|for|switch|case|default)\b[^{]*\{/g, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/[{}]/g, ' '))
    .replace(/\s+/g, ' ')
    .trim()
}

function attr(attrs, name) {
  const m = new RegExp(`(?:^|\\s)${name}="([^"]*)"`).exec(attrs)
  return m ? decode(m[1]) : ''
}

/** Must match slugForHelp() in shared/guide/help-search.ts. */
function slug(heading) {
  return heading.toLowerCase().replace(/[^a-z0-9]+/g, '-').slice(0, 60).replace(/^-+|-+$/g, '')
}

function entriesFor(file, tab) {
  const html = fs.readFileSync(path.join(TABS, file), 'utf8').replace(/<!--[\s\S]*?-->/g, '')
  const marker = /<h3([^>]*)>([\s\S]*?)<\/h3>|<rangertrak-expandable-section([^>]*)>/g
  const found = []
  let m
  while ((m = marker.exec(html))) {
    const isH3 = m[1] !== undefined
    const heading = isH3 ? plain(m[2]) : attr(m[3], 'summary')
    const id = attr(isH3 ? m[1] : m[3], 'id')
    if (heading) found.push({ heading, anchor: id || slug(heading), start: m.index, bodyFrom: marker.lastIndex })
  }
  return found.map((f, i) => ({
    tab,
    heading: f.heading,
    anchor: f.anchor,
    text: plain(html.slice(f.bodyFrom, i + 1 < found.length ? found[i + 1].start : html.length)),
  }))
}

function build() {
  const entries = FILES.flatMap(([file, tab]) => entriesFor(file, tab))
  return '// Generated by tools/help-index/build.js from src/app/lazy/help/tabs/*.html (E-264).\n'
    + '// Do not edit: change the templates and run `node tools/help-index/build.js`.\n'
    + 'export interface HelpIndexEntry { tab: string, heading: string, anchor: string, text: string }\n\n'
    + 'export const HELP_INDEX: readonly HelpIndexEntry[] = '
    + JSON.stringify(entries, null, 1).replace(/\n\s*/g, ' ').replace(/\}, \{/g, '},\n  {') + '\n'
}

const out = build()
if (process.argv.includes('--check')) {
  const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : ''
  if (now !== out) {
    console.error('help-index.generated.ts is out of date: run `node tools/help-index/build.js` and commit it.')
    process.exit(1)
  }
  console.log('OK: the Help search index matches the Help tabs.')
} else {
  fs.writeFileSync(OUT, out)
  console.log(`Wrote ${path.relative(ROOT, OUT)}`)
}
